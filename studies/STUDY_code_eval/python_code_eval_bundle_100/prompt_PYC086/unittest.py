def _strip_markdown_fences(response):
    text = response.strip()
    if text.startswith("```"):
        lines = text.splitlines()
        if lines and lines[0].startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].strip().startswith("```"):
            lines = lines[:-1]
        text = "\n".join(lines).strip()
    return text


def _load_response(response, task_id, required_symbol):
    code = _strip_markdown_fences(response)

    check_line = f"# CHECK_TOKEN: {task_id}"
    if check_line not in code:
        raise ValueError(f"missing required check token line: {check_line}")

    if required_symbol not in code:
        raise ValueError(f"missing required symbol: {required_symbol}")

    try:
        ast.parse(code)
    except SyntaxError as e:
        raise SyntaxError(f"syntax error: {e}") from e

    ns = {"__name__": "__candidate__"}
    exec(code, ns)
    return ns


